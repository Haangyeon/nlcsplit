#!/usr/bin/env python3
"""Summarize the two chemical controls in the exact rounded form quoted in the paper."""
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent


def read_json(path):
    return json.loads(path.read_text(encoding="utf-8"))


def orca_dnlc(directory, complex_name, fragment_names):
    vals = {}
    for name in [complex_name] + fragment_names:
        text = (HERE / directory / (name + ".out")).read_text(errors="ignore")
        m = re.search(r"NL Energy, E\(C,NL\)\s*:\s*([-+0-9.]+)", text)
        if not m:
            raise SystemExit("missing NL Energy in " + str(directory / name))
        vals[name] = float(m.group(1))
    return (vals[complex_name] - sum(vals[n] for n in fragment_names)) * 627.5094740631


def main():
    ab = read_json(HERE / "dative" / "ab_nlc.json")
    fw = read_json(HERE / "ionic" / "fw_nlc.json")
    ab_orca = orca_dnlc("dative", "ab_complex", ["ab_nh3", "ab_bh3"])
    fw_orca = orca_dnlc("ionic", "fw_complex", ["fw_f", "fw_water"])
    out = {
        "artifact_kind": "chemical_controls_summary",
        "dative": {
            "BN_A": round(ab["metrics"]["B-N_A"], 4),
            "span_L1": round(ab["rows"][0]["span"], 4),
            "span_L2": round(ab["rows"][1]["span"], 4),
            "pint_L1": {k: round(v, 4) for k, v in ab["rows"][0]["pint"].items()},
            "dnlc_L1": round(ab["rows"][0]["dnlc"], 4),
            "dnlc_L2": round(ab["rows"][1]["dnlc"], 4),
            "orca_dnlc": round(ab_orca, 4),
            "diff_pct_L1": round(abs(ab["rows"][0]["dnlc"] - ab_orca) / abs(ab_orca) * 100, 2),
            "diff_pct_L2": round(abs(ab["rows"][1]["dnlc"] - ab_orca) / abs(ab_orca) * 100, 2),
        },
        "ionic": {
            "FO_A": round(fw["metrics"]["F-O_A"], 4),
            "span_L1": round(fw["rows"][0]["span"], 4),
            "span_L2": round(fw["rows"][1]["span"], 4),
            "pint_L1": {k: round(v, 4) for k, v in fw["rows"][0]["pint"].items()},
            "dnlc_L1": round(fw["rows"][0]["dnlc"], 4),
            "dnlc_L2": round(fw["rows"][1]["dnlc"], 4),
            "orca_dnlc": round(fw_orca, 4),
            "diff_pct_L1": round(abs(fw["rows"][0]["dnlc"] - fw_orca) / abs(fw_orca) * 100, 2),
            "diff_pct_L2": round(abs(fw["rows"][1]["dnlc"] - fw_orca) / abs(fw_orca) * 100, 2),
        },
    }
    (HERE / "summary.json").write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")
    lines = ["# chemical_controls summary; generated by summarize.py"]
    for system in ("dative", "ionic"):
        for k, v in out[system].items():
            if isinstance(v, dict):
                for kk, vv in v.items():
                    lines.append("%s.%s.%s = %s" % (system, k, kk, vv))
            else:
                lines.append("%s.%s = %s" % (system, k, v))
    (HERE / "summary.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
